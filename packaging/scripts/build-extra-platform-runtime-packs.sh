    local package
    for package in \
        runtime/Microsoft.NETCore.App.Host.freebsd-x64.10.0.15.nupkg \
        runtime/Microsoft.NETCore.App.Runtime.freebsd-x64.10.0.15.nupkg \
        aspnetcore/Microsoft.AspNetCore.App.Runtime.freebsd-x64.10.0.15.nupkg; do
