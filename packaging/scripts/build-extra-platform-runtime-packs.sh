get_official_build_id() {
    local build_id="${DOTNET_OFFICIAL_BUILD_ID:-}"
    if [[ "$build_id" =~ ^20[0-9]{6}\.[0-9]+$ ]]; then
        printf '%s\n' "$build_id"
    else
        printf '%s.1\n' "$(date -u +%Y%m%d)"
    fi
}

require_sdk() {
    local version="$1"
    [ -x "$dotnet_root/dotnet" ] || die "dotnet was not found at $dotnet_root/dotnet"
    [ -f "$dotnet_root/sdk/$version/Microsoft.NETCoreSdk.BundledVersions.props" ] || die ".NET SDK $version must be installed under $dotnet_root"
}

verify_pinned_freebsd_source_versions() {
    # Check the immutable source revision before the large VMR clone. The runtime
    # and ASP.NET package assets are generated by the pinned source build below;
    # this preflight ensures that revision targets the required servicing version.
    python3 - "$freebsd_vmr_commit" "$runtime_version" <<'PY'
from urllib.request import Request, urlopen
import re
import sys

commit, expected = sys.argv[1:]
sources = (
    ("src/runtime/eng/Versions.props", "PatchVersion", "runtime"),
    ("src/aspnetcore/eng/Versions.props", "AspNetCorePatchVersion", "ASP.NET Core"),
)
for path, property_name, component in sources:
    url = f"https://raw.githubusercontent.com/dotnet/dotnet/{commit}/{path}"
    request = Request(url, headers={"User-Agent": "ChaptarrNG-runtime-pack-preflight"})
    try:
        with urlopen(request, timeout=20) as response:
            content = response.read(2 * 1024 * 1024).decode("utf-8")
    except Exception as exc:
        raise SystemExit(f"Could not verify pinned .NET VMR {component} version before cloning: {type(exc).__name__}")
    match = re.search(rf"<{property_name}>([^<]+)</{property_name}>", content)
    actual = match.group(1) if match else "missing"
    expected_patch = expected.rsplit(".", 1)[-1]
    if actual != expected_patch:
        raise SystemExit(
            f"Pinned .NET VMR {component} source has {property_name}={actual}; "
            f"expected .NET {expected} before cloning"
        )
PY
}

patch_sdk_runtime_ids() {
    local sdk_version="$1"
    local sdk_root="${2:-$dotnet_root}"
    local props="$sdk_root/sdk/$sdk_version/Microsoft.NETCoreSdk.BundledVersions.props"
    python3 - "$props" <<'PY'
from pathlib import Path
import re
import sys

path = Path(sys.argv[1])
content = path.read_text(encoding="utf-8-sig")

def patch(match):
    block = match.group(0)
    if 'TargetFramework="net10.0"' not in block:
        return block
    include = re.search(r'Include="([^"]+)"', block)
    if not include:
        return block
    package = include.group(1)
    attributes = []
    if package in ("Microsoft.NETCore.App", "Microsoft.AspNetCore.App"):
        attributes.append("RuntimePackRuntimeIdentifiers")
    if package == "Microsoft.NETCore.App":
        attributes.append("AppHostRuntimeIdentifiers")
    for attribute in attributes:
        attr = re.search(rf'{attribute}="([^"]*)"', block)
        if attr:
            values = attr.group(1).split(";")
            for rid in ("linux-x86", "freebsd-x64"):
                if rid not in values:
                    values.append(rid)
                    block = block[:attr.start(1)] + ";".join(values) + block[attr.end(1):]
                    attr = re.search(rf'{attribute}="([^"]*)"', block)
    return block

pattern = re.compile(r'<(?:KnownFrameworkReference|KnownAppHostPack)\s+Include="[^"]+"[\s\S]*?/>')
updated = pattern.sub(patch, content)
for framework in ("Microsoft.NETCore.App", "Microsoft.AspNetCore.App"):
    match = re.search(rf'<KnownFrameworkReference\s+Include="{re.escape(framework)}"[\s\S]*?TargetFramework="net10\.0"[\s\S]*?RuntimePackRuntimeIdentifiers="([^"]*)', updated)
    if not match or not {"linux-x86", "freebsd-x64"}.issubset(set(match.group(1).split(";"))):
        raise SystemExit(f"SDK metadata is missing custom .NET 10 runtime identifiers for {framework}")
path.write_text(updated, encoding="utf-8")
PY
}

clone_sources() {
    git clone --depth 1 --branch "$freebsd_vmr_tag" https://github.com/dotnet/dotnet.git "$freebsd_vmr_repo"
    local actual_commit
    actual_commit="$(git -C "$freebsd_vmr_repo" rev-parse HEAD)"
    [ "$actual_commit" = "$freebsd_vmr_commit" ] || die "Pinned .NET VMR tag resolved to unexpected commit $actual_commit"
    [ -f "$runtime_repo/eng/Versions.props" ] || die "Pinned .NET VMR is missing its runtime source tree"
    [ -f "$aspnet_repo/eng/Versions.props" ] || die "Pinned .NET VMR is missing its ASP.NET Core source tree"

    python3 - "$runtime_repo/eng/Versions.props" "$aspnet_repo/eng/Versions.props" "$runtime_version" <<'PY'
from pathlib import Path
import re
import sys

runtime_props = Path(sys.argv[1])
aspnet_props = Path(sys.argv[2])
version = sys.argv[3]
patch = version.rsplit(".", 1)[-1]

def verify(path, property_name):
    match = re.search(rf"<{property_name}>([^<]+)</{property_name}>", path.read_text())
    if not match or match.group(1) != patch:
        actual = match.group(1) if match else "missing"
        raise SystemExit(f"Pinned VMR {path.name} has {property_name}={actual}, expected {patch}")

verify(runtime_props, "PatchVersion")
verify(aspnet_props, "AspNetCorePatchVersion")
PY
}

